/**
 * Export helpers for the reports screen.
 *
 * Fixes, relative to the old export in sessions.tsx (docs/reporting-gaps.md):
 *   RPT-02  proper CSV quoting + UTF-8 BOM so Excel shows "Bañon" correctly
 *   RPT-02  a real .xls (SpreadsheetML) instead of HTML renamed .doc
 *   RPT-03  every file starts with a provenance block (period, dates, counts)
 *
 * The single most important rule here: an export never describes itself as the
 * whole period unless it actually contains every row. `assertComplete` throws if
 * a caller tries otherwise.
 */

import type { ReportMeta } from "@workspace/reporting";

export interface ExportContext {
  meta: ReportMeta;
  /** Name of the report, e.g. "Library Usage Summary". */
  title: string;
  /** Who generated it (from the admin session). */
  generatedBy?: string;
  /** Extra line under the header, e.g. "Utilisation assumes 08:00–17:00, Mon–Fri". */
  note?: string;
}

export class IncompleteExportError extends Error {
  constructor(shown: number, total: number) {
    super(
      `Refusing to export ${shown} of ${total} rows. An export must contain the whole ` +
        `filtered set, or say how many rows it left out.`,
    );
    this.name = "IncompleteExportError";
  }
}

/**
 * Guard against the LOG-08/RPT-03 failure: a truncated file that looks complete.
 * Call before exporting a paginated set.
 */
export function assertComplete(shown: number, total: number): void {
  if (shown < total) throw new IncompleteExportError(shown, total);
}

// ─── CSV ──────────────────────────────────────────────────────────────────────

/** RFC 4180 quoting: wrap in quotes and double any embedded quote. */
export function csvCell(value: unknown): string {
  if (value === null || value === undefined) return "";
  const text = String(value);
  // Quote when the value contains a delimiter, quote, or newline.
  if (/[",\r\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
  return text;
}

export function toCsv(headers: string[], rows: unknown[][]): string {
  const lines = [headers.map(csvCell).join(",")];
  for (const row of rows) lines.push(row.map(csvCell).join(","));
  return lines.join("\r\n");
}

/** Provenance lines as CSV rows (two columns: label, value). */
export function provenanceRows(ctx: ExportContext, rowCount?: number): string[][] {
  const { meta } = ctx;
  const rows: string[][] = [
    ["Report", ctx.title],
    ["Period", meta.label],
    ["From", meta.fromDate],
    ["To", meta.toDate],
    ["Timezone", meta.timezone],
    ["Generated at", new Date(meta.generatedAt).toLocaleString()],
    ["Generated by", ctx.generatedBy ?? "—"],
    ["Definitions version", meta.definitionsVersion],
  ];
  if (rowCount !== undefined) rows.push(["Rows in this file", String(rowCount)]);
  if (meta.includesToday) rows.push(["Note", "This period includes today, so the figures will still change."]);
  if (ctx.note) rows.push(["Method", ctx.note]);
  return rows;
}

/** Full CSV text: provenance block, blank line, then the table. */
export function buildCsv(ctx: ExportContext, headers: string[], rows: unknown[][]): string {
  const head = provenanceRows(ctx, rows.length)
    .map((r) => r.map(csvCell).join(","))
    .join("\r\n");
  return `${head}\r\n\r\n${toCsv(headers, rows)}`;
}

// ─── Download plumbing ───────────────────────────────────────────────────────

/** UTF-8 BOM — without this Excel mis-reads accented names (RPT-02). */
const BOM = "\uFEFF";

export function downloadText(filename: string, text: string, mime: string): void {
  // Excel on Windows needs the BOM to detect UTF-8.
  const blob = new Blob([BOM + text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  // Give the browser a tick before revoking.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Filesystem-safe slug for the period, e.g. "2026-11-01_to_2026-11-30". */
export function periodSlug(meta: ReportMeta): string {
  return `${meta.fromDate}_to_${meta.toDate}`;
}

export function exportCsv(ctx: ExportContext, headers: string[], rows: unknown[][]): void {
  const name = `${slug(ctx.title)}_${periodSlug(ctx.meta)}.csv`;
  downloadText(name, buildCsv(ctx, headers, rows), "text/csv");
}

function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

// ─── Excel (SpreadsheetML: opens natively, no library, keeps numbers typed) ──

function xmlEscape(value: unknown): string {
  if (value === null || value === undefined) return "";
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * A minimal multi-sheet .xls. Real cells (numbers stay numbers, no column
 * merging weirdness) and it opens in Excel, LibreOffice and Google Sheets.
 */
export function buildXls(sheets: { name: string; headers: string[]; rows: unknown[][] }[]): string {
  const sheetXml = sheets
    .map((sheet) => {
      const headerCells = sheet.headers
        .map((h) => `<Cell ss:StyleID="head"><Data ss:Type="String">${xmlEscape(h)}</Data></Cell>`)
        .join("");
      const bodyRows = sheet.rows
        .map((row) => {
          const cells = row
            .map((v) => {
              const isNumber = typeof v === "number" && Number.isFinite(v);
              return `<Cell><Data ss:Type="${isNumber ? "Number" : "String"}">${xmlEscape(v)}</Data></Cell>`;
            })
            .join("");
          return `<Row>${cells}</Row>`;
        })
        .join("");
      return `<Worksheet ss:Name="${xmlEscape(sheet.name.slice(0, 31))}"><Table><Row>${headerCells}</Row>${bodyRows}</Table></Worksheet>`;
    })
    .join("");

  return `<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">
 <Styles>
  <Style ss:ID="head"><Font ss:Bold="1"/><Interior ss:Color="#DCE6F1" ss:Pattern="Solid"/></Style>
 </Styles>
 ${sheetXml}
</Workbook>`;
}

export function exportXls(
  ctx: ExportContext,
  sheets: { name: string; headers: string[]; rows: unknown[][] }[],
): void {
  // Prepend the provenance as its own sheet so the file explains itself.
  const provenance = {
    name: "About",
    headers: ["Field", "Value"],
    rows: provenanceRows(ctx),
  };
  const name = `${slug(ctx.title)}_${periodSlug(ctx.meta)}.xls`;
  downloadText(name, buildXls([provenance, ...sheets]), "application/vnd.ms-excel");
}

// ─── PDF (print view) ───────────────────────────────────────────────────────

/**
 * Opens the dedicated print view in a new tab. The print view renders the same
 * numbers and a provenance header, with @page rules for A4 landscape — this
 * replaces the old "window.open + document.write of a table string" approach
 * (RPT-02), which had no header, no margins and popup-blocker failure modes.
 *
 * Returns false when a popup blocker prevented the window from opening, so the
 * caller can show a toast instead of failing silently.
 */
export function openPrintView(url: string): boolean {
  const win = window.open(url, "_blank");
  if (!win) return false;
  return true;
}
