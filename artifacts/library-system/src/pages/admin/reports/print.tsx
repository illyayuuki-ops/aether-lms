/**
 * Print / PDF view for a report.
 *
 * Why a dedicated route instead of printing the screen (the old approach):
 *   - a fixed @page layout (A4 landscape) that does not depend on browser zoom
 *   - a cover block with school, period, resolved dates, generated-by/at, and
 *     the definitions version — the provenance a citation needs (RPT-02)
 *   - charts render from the same components as the screen, so the figure on
 *     paper is the figure in the app
 *
 * Open with: /admin/reports/print?period=this_month  (or ?period=custom&from=…&to=…)
 */
import { useEffect, useState } from "react";
import { humanMinutes, percent, type ReportOverviewResponse } from "@workspace/reporting";
import { DailyTrendChart, HourlyOccupancyChart, WeekdayHourHeatmap, formatHour } from "./charts";
import { OUTCOME_LABELS } from "./index";

const OUTCOME_FALLBACK: Record<string, string> = {
  manual: "Logged out by student",
  inactivity: "Ended automatically (inactivity)",
  time_limit: "Ended at the time limit",
  librarian: "Ended by librarian",
  active: "Still active",
  unknown: "Not recorded",
};

export default function ReportPrintPage() {
  const [data, setData] = useState<ReportOverviewResponse | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    const token = localStorage.getItem("admin_token");
    fetch(`/api/reports/overview?${window.location.search.replace(/^\?/, "")}`, {
      headers: token ? { Authorization: `Bearer ${token}` } : {},
    })
      .then(async (r) => {
        if (!r.ok) throw new Error((await r.json().catch(() => ({}))).message ?? `HTTP ${r.status}`);
        return r.json();
      })
      .then((d: ReportOverviewResponse) => {
        setData(d);
        // Let charts paint before opening the dialog.
        setTimeout(() => window.print(), 600);
      })
      .catch((e) => setError(e instanceof Error ? e.message : "Failed to load report."));
  }, []);

  if (error) {
    return (
      <div className="p-8 text-sm">
        <p className="font-semibold text-destructive">Could not load the report</p>
        <p className="mt-1 text-muted-foreground">{error}</p>
      </div>
    );
  }

  if (!data) return <div className="p-8 text-sm text-muted-foreground">Preparing print view…</div>;

  const { meta, summary, daily, hours, byCourse, byYearLevel, weekdayHour, quality } = data;
  const generatedBy = localStorage.getItem("admin_username") || "—";
  const labels = Object.keys(OUTCOME_LABELS).length ? OUTCOME_LABELS : OUTCOME_FALLBACK;

  return (
    <div className="report-print bg-white text-black">
      <style>{`
        @page { size: A4 landscape; margin: 12mm; }
        @media print {
          .no-print { display: none !important; }
          .page-break { break-before: page; }
        }
        .report-print { font-family: Arial, Helvetica, sans-serif; font-size: 10px; }
        .report-print h1 { font-size: 18px; margin: 0; }
        .report-print h2 { font-size: 12px; margin: 14px 0 6px; color: #1e3a5f; }
        .report-print table { border-collapse: collapse; width: 100%; }
        .report-print th { background: #1e3a5f; color: #fff; text-align: left; padding: 4px 6px; font-size: 9px; }
        .report-print td { padding: 3px 6px; border-bottom: 1px solid #ddd; font-size: 9px; }
        .report-print tr:nth-child(even) td { background: #f8fafc; }
      `}</style>

      {/* Provenance block — the part that makes this citable */}
      <header style={{ borderBottom: "2px solid #1e3a5f", paddingBottom: 8, marginBottom: 10 }}>
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start" }}>
          <div>
            <h1>Library Usage Report</h1>
            <p style={{ margin: "2px 0 0", fontSize: 11, color: "#334155" }}>{meta.label}</p>
          </div>
          <div style={{ textAlign: "right", fontSize: 9, color: "#475569", lineHeight: 1.5 }}>
            <div><strong>Period:</strong> {meta.fromDate} → {meta.toDate}</div>
            <div><strong>Days covered:</strong> {meta.days}</div>
            <div><strong>Timezone:</strong> {meta.timezone}</div>
            <div><strong>Generated:</strong> {new Date(meta.generatedAt).toLocaleString()}</div>
            <div><strong>Generated by:</strong> {generatedBy}</div>
            <div><strong>Definitions:</strong> v{meta.definitionsVersion}</div>
          </div>
        </div>
        {meta.includesToday && (
          <p style={{ margin: "6px 0 0", fontSize: 9, color: "#b45309" }}>
            This period includes today, so these figures will still change.
          </p>
        )}
      </header>

      {/* Headline numbers */}
      <h2>1. Summary</h2>
      <table>
        <thead>
          <tr>
            {["Sessions", "Unique students", "Reach", "Total PC time", "Average session", "Median", "Utilisation"].map((h) => (
              <th key={h}>{h}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          <tr>
            <td>{summary.totalSessions.toLocaleString()}</td>
            <td>{summary.uniqueStudents.toLocaleString()}</td>
            <td>{summary.reachPct === null ? "not recorded" : `${summary.reachPct}% of ${summary.enrolledStudents.toLocaleString()}`}</td>
            <td>{humanMinutes(summary.totalMinutes)}</td>
            <td>{humanMinutes(summary.avgSessionMinutes)}</td>
            <td>{humanMinutes(summary.medianSessionMinutes)}</td>
            <td>{summary.utilisationPct === null ? "unknown" : `${summary.utilisationPct}%`}</td>
          </tr>
        </tbody>
      </table>

      <h2>2. Sessions per day</h2>
      <DailyTrendChart data={daily} height={150} />

      <h2>3. PC occupancy by hour</h2>
      <HourlyOccupancyChart data={hours} height={150} />

      <div className="page-break" />

      <h2>4. Weekday × hour distribution</h2>
      <WeekdayHourHeatmap grid={weekdayHour} />

      <h2>5. Usage by course</h2>
      <table>
        <thead>
          <tr>
            {["Course", "Sessions", "Students", "Avg session", "Total time", "Share"].map((h) => <th key={h}>{h}</th>)}
          </tr>
        </thead>
        <tbody>
          {byCourse.map((c) => (
            <tr key={c.degree}>
              <td>{c.degree}</td>
              <td>{c.sessions.toLocaleString()}</td>
              <td>{c.uniqueStudents}</td>
              <td>{humanMinutes(c.avgSessionMinutes)}</td>
              <td>{humanMinutes(c.totalMinutes)}</td>
              <td>{c.sharePct}%</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2>6. Usage by year level</h2>
      <table>
        <thead>
          <tr>{["Year level", "Sessions", "Students", "Share"].map((h) => <th key={h}>{h}</th>)}</tr>
        </thead>
        <tbody>
          {byYearLevel.map((y) => (
            <tr key={y.yearLevel}>
              <td>{y.yearLevel}</td>
              <td>{y.sessions.toLocaleString()}</td>
              <td>{y.uniqueStudents}</td>
              <td>{y.sharePct}%</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2>7. How sessions ended</h2>
      <table>
        <thead>
          <tr>{["Outcome", "Sessions", "Share"].map((h) => <th key={h}>{h}</th>)}</tr>
        </thead>
        <tbody>
          {summary.byOutcome.map((o) => (
            <tr key={o.outcome}>
              <td>{labels[o.outcome] ?? o.outcome}</td>
              <td>{o.count.toLocaleString()}</td>
              <td>{percent(o.count, summary.totalSessions)}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2>8. Data quality &amp; method notes</h2>
      <table>
        <thead>
          <tr>{["Check", "Count", "How it was handled"].map((h) => <th key={h}>{h}</th>)}</tr>
        </thead>
        <tbody>
          {quality.issues.length === 0 ? (
            <tr><td colSpan={3}>No data-quality issues found in this period.</td></tr>
          ) : (
            quality.issues.map((i) => (
              <tr key={i.code}>
                <td>{i.label}</td>
                <td>{i.count}</td>
                <td>{i.treatment}</td>
              </tr>
            ))
          )}
        </tbody>
      </table>

      <p style={{ marginTop: 10, fontSize: 8, color: "#64748b" }}>
        Definitions v{meta.definitionsVersion} · Average and median durations exclude sessions shorter than one
        minute and sessions that are still active · Utilisation = total session minutes ÷ (configured PCs ×
        library open hours) · Day boundaries computed in {meta.timezone} · Generated by Aether LMS.
      </p>
    </div>
  );
}
