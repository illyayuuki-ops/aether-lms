/**
 * Export correctness tests. These exist because a broken CSV that *looks* fine
 * is the single most likely way a wrong number reaches a paper (RPT-02).
 *
 * Run: pnpm --dir artifacts/library-system test
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  csvCell,
  toCsv,
  buildCsv,
  provenanceRows,
  buildXls,
  assertComplete,
  IncompleteExportError,
  periodSlug,
} from "./export";
import type { ReportMeta } from "@workspace/reporting";

const meta: ReportMeta = {
  label: "1st Semester AY 2026-2027 (15 Jun 2026 – 31 Oct 2026)",
  period: "custom",
  fromDate: "2026-06-15",
  toDate: "2026-10-31",
  timezone: "Asia/Manila",
  days: 139,
  includesToday: false,
  generatedAt: "2026-11-06T02:00:00.000Z",
  definitionsVersion: "2026-11-06",
};

const ctx = { meta, title: "Library Usage Summary", generatedBy: "librarian01" };

// ─── Cell quoting ───────────────────────────────────────────────────────────

test("plain values are not quoted", () => {
  assert.equal(csvCell("BSIT"), "BSIT");
  assert.equal(csvCell(42), "42");
});

test("commas, quotes and newlines are escaped, not left to break columns", () => {
  assert.equal(csvCell("ARTS & DESIGN, TVL"), '"ARTS & DESIGN, TVL"');
  assert.equal(csvCell('Maria "May" Santos'), '"Maria ""May"" Santos"');
  assert.equal(csvCell("line1\nline2"), '"line1\nline2"');
});

test("null and undefined become empty cells, not the text 'null'", () => {
  assert.equal(csvCell(null), "");
  assert.equal(csvCell(undefined), "");
});

test("a name with a comma keeps the column count intact", () => {
  const csv = toCsv(["Name", "Course"], [["Santos, Maria", "BSIT"]]);
  const [header, row] = csv.split("\r\n");
  // Naive splitting would give 3 fields here; correct quoting gives 2.
  assert.equal(countFields(header), 2);
  assert.equal(countFields(row), 2);
});

/** Count CSV fields honouring quotes. */
function countFields(line: string): number {
  let fields = 1;
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') { i++; continue; }
      inQuotes = !inQuotes;
    } else if (ch === "," && !inQuotes) fields++;
  }
  return fields;
}

// ─── Provenance ─────────────────────────────────────────────────────────────

test("provenance states the period AND the resolved dates", () => {
  const rows = provenanceRows(ctx, 1284);
  const get = (label: string) => rows.find((r) => r[0] === label)?.[1];
  assert.equal(get("Period"), meta.label);
  assert.equal(get("From"), "2026-06-15");
  assert.equal(get("To"), "2026-10-31");
  assert.equal(get("Timezone"), "Asia/Manila");
  assert.equal(get("Rows in this file"), "1284");
  assert.equal(get("Generated by"), "librarian01");
  assert.equal(get("Definitions version"), "2026-11-06");
});

test("a period that includes today carries a warning that numbers will move", () => {
  const moving = provenanceRows({ ...ctx, meta: { ...meta, includesToday: true } });
  assert.ok(moving.some((r) => r[0] === "Note" && /still change/i.test(r[1])));
  const settled = provenanceRows(ctx);
  assert.ok(!settled.some((r) => r[0] === "Note"));
});

test("the full CSV begins with provenance, then a blank line, then the table", () => {
  const csv = buildCsv(ctx, ["Course", "Sessions"], [["BSIT", 120]]);
  const blocks = csv.split("\r\n\r\n");
  assert.equal(blocks.length, 2);
  assert.match(blocks[0], /^Report,Library Usage Summary/);
  assert.equal(blocks[1], "Course,Sessions\r\nBSIT,120");
});

// ─── Completeness guard ────────────────────────────────────────────────────

test("exporting fewer rows than the filter matched is refused", () => {
  assert.throws(() => assertComplete(50, 1284), IncompleteExportError);
  assert.doesNotThrow(() => assertComplete(1284, 1284));
});

test("the guard message names both numbers", () => {
  try {
    assertComplete(50, 1284);
    assert.fail("should have thrown");
  } catch (err) {
    assert.match((err as Error).message, /50 of 1284 rows/);
  }
});

// ─── Excel ─────────────────────────────────────────────────────────────────

test("xls output escapes XML and keeps numbers numeric", () => {
  const xls = buildXls([
    { name: "Summary", headers: ["Course", "Sessions"], rows: [["BSIT & IT", 120], ["BSED", 40]] },
  ]);
  assert.match(xls, /BSIT &amp; IT/);
  assert.match(xls, /<Data ss:Type="Number">120<\/Data>/);
  assert.match(xls, /<Data ss:Type="String">BSED<\/Data>/);
  assert.match(xls, /progid="Excel.Sheet"/);
});

test("xls sheet names are truncated to Excel's 31-character limit", () => {
  const xls = buildXls([
    { name: "A very long sheet name that Excel would reject outright", headers: ["a"], rows: [] },
  ]);
  const match = xls.match(/ss:Name="([^"]+)"/);
  assert.ok(match && match[1].length <= 31, `got ${match?.[1]}`);
});

// ─── Filenames ─────────────────────────────────────────────────────────────

test("filenames are derived from the resolved dates, not 'today'", () => {
  assert.equal(periodSlug(meta), "2026-06-15_to_2026-10-31");
});
